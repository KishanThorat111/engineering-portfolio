/**
 * INSTANT PREVIEWS OF THE TEN PLATES — what a frame shows before its artwork
 * has arrived.
 *
 * Measured on a 3G connection, the home page's opening text painted at 1.5s
 * and its artwork at 6–8s; until then every frame was the empty graphite
 * ground, which reads as a page that has not finished loading. Each plate now
 * has a preview of about 250 bytes: the artwork shrunk to 64px, softened, and
 * drawn as the plate element's own background, so a frame shows its scene's
 * colours and shapes on first paint and the full artwork simply lands over it.
 *
 * THE PREVIEWS ARE A STYLESHEET, NOT INLINE STYLES. They ship as one rule per
 * plate, `[data-preview='02-systems'] { background-image: url(…) }`, in a
 * generated CSS file every page that shows a plate imports. Carried in a
 * `style` attribute instead, a data URI's `;base64,` reads to the HTML gate as
 * a second, undeclared inline property — so the previews live where CSS lives.
 *
 * Made from the PUBLISHED 768px WebP of each plate, not from the masters, so a
 * preview carries every treatment the plate has (fades, defocused regions) and
 * this needs nothing that is not committed. The record beside the stylesheet
 * says which file each preview came from; station-check fails the build when
 * that is no longer the plate the manifest names, so a re-encoded plate cannot
 * ship with a stale preview. Output is byte-identical across runs.
 *
 * usage: npm run assets:previews
 */
import sharp from 'sharp';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, join } from 'node:path';

const MANIFEST = resolve('apps/static/src/config/visual-world-manifest.json');
const PLATES = resolve('apps/static/public/visual-world');
const RECORD = resolve('apps/static/src/config/visual-world-previews.json');
const SHEET = resolve('apps/static/src/styles/plate-previews.css');

/*
 * 64 × 43 keeps the plates' 3:2 to within a pixel. Compared on screen against
 * 32 and 48, it is the smallest at which these dark plates still read as their
 * scene (the tower's glow, the owner at his desk) rather than as a smudge. The
 * slight blur before encoding is what lets the browser's own upscaling read as
 * soft focus rather than as blocks.
 */
const W = 64;
const H = 43;

const manifest = JSON.parse(readFileSync(MANIFEST, 'utf8'));
const record = {};
const rules = [];
let total = 0;

for (const [stem, entry] of Object.entries(manifest)) {
  const from = entry.webp?.['768'];
  if (!from) throw new Error(`visual-world-previews: ${stem} has no 768px WebP to preview from`);
  const tiny = await sharp(join(PLATES, from))
    .resize(W, H, { fit: 'fill' })
    .blur(0.6)
    .webp({ quality: 55, effort: 6 })
    .toBuffer();
  const uri = `data:image/webp;base64,${tiny.toString('base64')}`;
  record[stem] = { from, bytes: tiny.length };
  rules.push(`[data-preview='${stem}'] {\n  background-image: url('${uri}');\n}`);
  total += uri.length;
  console.log(`  ${stem.padEnd(14)} ${String(tiny.length).padStart(4)} bytes  (from ${from})`);
}

writeFileSync(
  SHEET,
  `/*\n * GENERATED by scripts/visual-world-previews.mjs — do not edit by hand.\n` +
    ` * Instant previews of the ten plates; see that script for why.\n */\n\n` +
    `${rules.join('\n\n')}\n`,
);
writeFileSync(RECORD, `${JSON.stringify(record, null, 2)}\n`);
console.log(`\n  ${rules.length} previews, ${total} bytes of CSS → ${SHEET}`);
